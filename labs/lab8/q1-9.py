# PRACTICE PROBLEM 1 (easy). COUNT OCCURRENCES
# Return the number of times e appears in the list L, recursively.
#   count_occurrences([1, 2, 1, 3, 1], 1)    -> 3
#   count_occurrences([], 5)                 -> 0
#   count_occurrences(["a", "b", "a"], "c")  -> 0
def count_occurrences(L, e):
    def recurse(L, count):
        if not L:
            return count
        if L[0] == e:
            count += 1
        return recurse(L[1::], count)

    return recurse(L, 0)


def count_occurrences_gemini(L, e):
    if not L:
        return 0
    return (1 if L[0] == e else 0) + count_occurrences_gemini(L[1:], e)


# PRACTICE PROBLEM 2 (medium). PALINDROME
# Return True if the string s reads the same forwards and backwards,
# and False otherwise, recursively.
#   is_palindrome("racecar")  -> True
#   is_palindrome("ab")       -> False
#   is_palindrome("")         -> True
def is_palindrome(s):
    if len(s) <= 1:
        return True
    if s[0] == s[-1]:
        return is_palindrome(s[1:-1])
    else:
        return False


def is_palindrome_gemini(s):
    def helper(l, r):
        if l >= r:
            return True
        if s[l] != s[r]:
            return False
        return helper(l + 1, r - 1)

    return helper(0, len(s) - 1)


# PRACTICE PROBLEM 3 (hard). GRID PATHS
# A grid has rows rows and cols cols (both at least 1). You start in the
# top-left cell and can move only one cell right or one cell down. Return the
# number of different paths to the bottom-right cell, recursively.
#   count_paths(2, 2)  -> 2
#   count_paths(3, 3)  -> 6
#   count_paths(1, 5)  -> 1
def count_paths(rows, cols):
    count = 0

    def recurse(x, y):
        nonlocal count
        if x == cols and y == rows:
            count += 1
            return
        if x < cols:
            recurse(x + 1, y)
        if y < rows:
            recurse(x, y + 1)

    recurse(1, 1)
    return count


def count_paths_gemini(rows, cols):
    if rows == 1 or cols == 1:
        return 1
    return count_paths_gemini(rows - 1, cols) + count_paths_gemini(rows, cols - 1)


